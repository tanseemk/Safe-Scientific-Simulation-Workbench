"""Generates reference pages from the canonical contract. `--check` fails on drift."""
from __future__ import annotations

import json
import sys
from pathlib import Path

from . import contract as C

DOCS = C.ROOT / "docs" / "reference"


def _head(title: str) -> list[str]:
    e = C.ext()
    return [f"<!-- GENERATED by scripts/build_docs.py from packages/contracts/schema/settings.v1.json. Do not edit. -->", "",
            f"# {title}", "",
            f"- **Schema version:** {e['schema_version']}",
            f"- **Model:** {e['model']['title']} — `{e['model']['equation']}`",
            f"- **Solver method:** {e['model']['solver']}",
            f"- **Canonical units:** SI (kg, N/m, N·s/m, m, m/s, s). Only the declared unit set is normalised.", ""]


def _assumptions() -> list[str]:
    m = C.ext()["model"]
    return (["## Assumptions", ""] + [f"- {a}" for a in m["assumptions"]] + ["", "## Limits", ""] + [f"- {a}" for a in m["limits"]]
            + ["", f"Step rule: {m['step_rule']}", f"Reference: {m['reference']}", ""])


def settings_page() -> str:
    e = C.ext()
    L = _head("Settings reference")
    L += ["Each numeric field is a quantity object `{\"value\": number, \"unit\": string}`. Unknown fields are rejected. "
          "Bounds are versioned engineering/resource limits, not physical laws.", "",
          "| Field | Symbol | Canonical unit | Accepted units (factor to canonical) | Min | Max | Offered default | Description |",
          "|---|---|---|---|---|---|---|---|"]
    for name, s in C.field_specs().items():
        units = ", ".join(f"`{u}` (×{f:g})" for u, f in s["units"].items())
        L.append(f"| `{name}` | {s['symbol']} | `{s['canonical_unit']}` | {units} | {s['min']:g} | {s['max']:g} | {s['default']:g} | {s['description']} |")
    L += ["", "`model` must be one of: " + ", ".join(f"`{m}`" for m in C.load_contract()["properties"]["model"]["enum"]) + ".", "",
          f"**Defaults policy.** {e['defaults_policy']}", "",
          "## Cross-field limits", "",
          f"- Integration steps `ceil(duration/dt)` must not exceed **{e['max_steps']:,}**.",
          "- `dt` must not exceed `duration`.",
          f"- Fastest rate × dt ≥ **{e['stability']['warn_omega_dt']}** raises a warning; ≥ **{e['stability']['reject_omega_dt']}** is rejected (outside the RK4 stability region).",
          f"- Feedback mode allows at most **{e['retry_cap']}** retries (three attempts in total).", "",
          "## Unit aliases", "", ", ".join(f"`{a}` → `{c}`" for a, c in e["unit_aliases"].items()), ""]
    return "\n".join(L + _assumptions())


def rules_page() -> str:
    L = _head("Validation rules")
    L += ["Every issue carries `path`, `rule_id`, `severity`, `kind`, `message` and `guidance`. `kind` decides the disposition: "
          "`clarify` → ask the user; `reject` → refuse without calling the solver; `warn` → informational; `output` → output check.", "",
          "| Rule ID | Kind | Severity | Meaning | Corrective guidance |", "|---|---|---|---|---|"]
    for r in C.ext()["rules"]:
        L.append(f"| `{r['id']}` | {r['kind']} | {r['severity']} | {r['title']} | {r['guidance']} |")
    L += ["", "## Example messages", "",
          "- `settings.mass: required field is missing.`", "- `settings.duration: supply s; “5” has no unit.`",
          "- `settings.dt: 0.2 s exceeds maximum 0.05 s.`", "- `settings: 500,000 integration steps exceeds cap of 200,000.`",
          "- `result.displacement: non-finite value at index 34.`", ""]
    return "\n".join(L + _assumptions())


def corpus_page() -> str:
    with open(C.PROMPTS_PATH, encoding="utf-8") as fh:
        suite = json.load(fh)
    L = _head("Fixed prompt corpus")
    L += [f"Suite `{suite['suite']}` v{suite['version']}, frozen {suite['frozen_on']}. {suite['note']}", "",
          "| ID | Type | Prompt | Expected | Expected rules |", "|---|---|---|---|---|"]
    for p in suite["prompts"]:
        L.append(f"| {p['id']} | {p['type']} | {p['prompt'].replace('|', '\\|')} | {p['expected']} | {', '.join(p['expected_rules']) or '—'} |")
    return "\n".join(L + [""] + _assumptions())


PAGES = {"settings.md": settings_page, "validation-rules.md": rules_page, "prompt-corpus.md": corpus_page}


def main(argv=None) -> int:
    check = "--check" in (argv if argv is not None else sys.argv[1:])
    stale = []
    DOCS.mkdir(parents=True, exist_ok=True)
    for name, fn in PAGES.items():
        text = fn()
        path = DOCS / name
        if check:
            current = path.read_text(encoding="utf-8").replace("\r\n", "\n") if path.exists() else None
            if current != text:
                stale.append(str(path.relative_to(C.ROOT)))
        else:
            path.write_text(text, encoding="utf-8", newline="\n")
            print(f"wrote {path.relative_to(C.ROOT)}")
    if stale:
        print("STALE generated docs (run `npm run docs:build`): " + ", ".join(stale), file=sys.stderr)
        return 1
    if check:
        print("generated docs are current")
    return 0


if __name__ == "__main__":
    sys.exit(main())
